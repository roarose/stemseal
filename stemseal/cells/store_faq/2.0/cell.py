def cell_executor(inp):
    q = inp.get("question")
    if not isinstance(q, str) or not q.strip():
        raise ValueError("pass question: the customer's whole sentence, unchanged")
    extra = sorted(str(k) for k in inp if k not in ("question", "faq"))
    if extra:
        raise ValueError("unknown input %s; use question and faq" % extra[:3])
    faq = inp.get("faq")
    if not isinstance(faq, list) or not faq:
        raise ValueError("pass faq: the store's list [{id, keys: [words], answer: text or null}] from the store's data")
    nq = norm(q); best = []; top = 0
    for e in faq:
        if not isinstance(e, dict) or not isinstance(e.get("id"), str) or not isinstance(e.get("keys"), list) or not (e.get("answer") is None or isinstance(e.get("answer"), str)):
            raise ValueError("each faq entry needs id (text), keys (list of words) and answer (text, or null when the store has no answer yet)")
        score = sum(len(norm(k)) for k in e["keys"] if isinstance(k, str) and norm(k) and norm(k) in nq)
        if score > top:
            best, top = [e], score
        elif score and score == top:
            best.append(e)
    out = {"answer_ready": False, "faq_id": None, "answer": None, "ask_staff": True}
    if len(best) != 1:   # nothing fits, or two answers fit equally: a person should answer, not a guess
        return out
    e = best[0]; out["faq_id"] = e["id"]
    if e["answer"]:
        out.update(answer_ready=True, answer=e["answer"], ask_staff=False)
    return out
